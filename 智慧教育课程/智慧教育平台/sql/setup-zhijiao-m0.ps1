# 一键创建 zhijiao_m0 并导入演示数据（Windows PowerShell）
# 用法:
#   .\setup-zhijiao-m0.ps1 -MySqlPassword '你的密码'
#   .\setup-zhijiao-m0.ps1 -MySqlPassword '你的密码' -WriteEnv

param(
    [string]$MySqlUser = 'root',
    [Parameter(Mandatory = $true)]
    [string]$MySqlPassword,
    [string]$Database = 'zhijiao_m0',
    [string]$MySqlExe = 'C:\Program Files\MySQL\MySQL Server 8.0\bin\mysql.exe',
    [switch]$WriteEnv,
    [switch]$ForceRecreate
)

$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$sqlDir = $PSScriptRoot
$backendDir = Join-Path $root 'backend'
$envFile = Join-Path $backendDir '.env'
$envExample = Join-Path $backendDir '.env.example'

if (-not (Test-Path -LiteralPath $MySqlExe)) {
    throw "未找到 mysql.exe：$MySqlExe"
}

$scripts = @(
    (Join-Path $sqlDir 'upstream\ruoyi\ry_20260417.sql'),
    (Join-Path $sqlDir 'upstream\ruoyi\quartz.sql'),
    (Join-Path $sqlDir 'mysql-v3-m0-core-schema.sql'),
    (Join-Path $sqlDir 'mysql-v3-m0-teaching-schema.sql'),
    (Join-Path $sqlDir 'demo-v3-m0-seed.sql'),
    (Join-Path $sqlDir 'demo-v3-m0-ruoyi-login-seed.sql')
)

foreach ($script in $scripts) {
    if (-not (Test-Path -LiteralPath $script)) {
        throw "缺少 SQL 文件：$script"
    }
}

function Invoke-MySql([string]$Sql, [string]$DatabaseName = $null) {
    $args = @('-u', $MySqlUser, "-p$MySqlPassword", '--default-character-set=utf8mb4', '-e', $Sql)
    if ($DatabaseName) {
        $args = @('-u', $MySqlUser, "-p$MySqlPassword", '--default-character-set=utf8mb4', '--database', $DatabaseName, '-e', $Sql)
    }
    & $MySqlExe @args | Out-Null
    if ($LASTEXITCODE -ne 0) {
        throw "MySQL 命令失败：$Sql"
    }
}

function Import-SqlFile([string]$Path, [string]$DatabaseName) {
    Write-Host "导入: $([IO.Path]::GetFileName($Path))"
    $args = @('-u', $MySqlUser, "-p$MySqlPassword", '--default-character-set=utf8mb4', '--database', $DatabaseName)
    Get-Content -LiteralPath $Path -Raw -Encoding UTF8 | & $MySqlExe @args
    if ($LASTEXITCODE -ne 0) {
        throw "导入失败：$Path"
    }
}

Write-Host "检查 MySQL 连接..."
Invoke-MySql 'SELECT VERSION();'

if ($ForceRecreate) {
    Write-Host "删除并重建数据库 $Database ..."
    Invoke-MySql "DROP DATABASE IF EXISTS ``$Database``;"
}

Write-Host "创建数据库 $Database ..."
Invoke-MySql "CREATE DATABASE IF NOT EXISTS ``$Database`` DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci;"

foreach ($script in $scripts) {
    Import-SqlFile -Path $script -DatabaseName $Database
}

Write-Host "验证导入结果..."
$verify = @(
    "SELECT COUNT(*) AS sys_user_count FROM sys_user;",
    "SELECT COUNT(*) AS edu_session_count FROM edu_class_session;",
    "SELECT user_name FROM sys_user WHERE user_name IN ('admin','teacher','student') ORDER BY user_name;"
) -join ' '

& $MySqlExe -u $MySqlUser "-p$MySqlPassword" --default-character-set=utf8mb4 --database $Database -e $verify
if ($LASTEXITCODE -ne 0) {
    throw '验证查询失败'
}

if ($WriteEnv) {
    if (-not (Test-Path -LiteralPath $envExample)) {
        throw "缺少 .env.example"
    }
    $token = [Guid]::NewGuid().ToString('N') + [Guid]::NewGuid().ToString('N')
    $url = "jdbc:mysql://localhost:3306/${Database}?useUnicode=true&characterEncoding=utf8&zeroDateTimeBehavior=convertToNull&useSSL=false&serverTimezone=UTC&allowPublicKeyRetrieval=true"
    $content = @(
        '# Generated by sql/setup-zhijiao-m0.ps1',
        "RUOYI_DB_URL=$url",
        "RUOYI_DB_USERNAME=$MySqlUser",
        "RUOYI_DB_PASSWORD=$MySqlPassword",
        "RUOYI_TOKEN_SECRET=$token",
        'RUOYI_REDIS_HOST=localhost',
        'RUOYI_REDIS_PORT=6379',
        'RUOYI_REDIS_DATABASE=15',
        'RUOYI_REDIS_PASSWORD='
    ) -join "`n"
    Set-Content -LiteralPath $envFile -Value $content -Encoding UTF8
    Write-Host "已写入 $envFile"
}

Write-Host ''
Write-Host '完成。数据库 zhijiao_m0 已就绪。'
Write-Host '演示账号见 docs/demo-login-accounts.txt（teacher/teacher123, student/student123, admin/admin123）'
